    !> Collect all exported unit tests.
    subroutine collect_itree_fm(testsuite)
        type(unittest_type), allocatable, intent(out) :: testsuite(:)

        testsuite = [ &
                    new_unittest("overlay-make-move-delete", test_basics), &
