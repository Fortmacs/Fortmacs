                    new_unittest("test-overlay-lists-1", test_overlay_lists_1), &
                    new_unittest("test-overlay-recenter", test_overlay_recenter) &
                    ]
    end subroutine collect_itree_fm

    !> A fresh buffer holding TEXT.
    subroutine fresh(h, text)
        type(handle_type), intent(out) :: h
        character(len=*), intent(in) :: text
        type(status_type) :: st

        call get_or_make_buffer("*itree-test*", h, st)
        call set_buffer(h, st)
        call insert(text, st)
    end subroutine fresh

    !> make-overlay orders and clips its bounds; move-overlay; deleted
    !> overlays have no buffer and no bounds.
    subroutine test_basics(error)
        type(error_type), allocatable, intent(out) :: error
        type(handle_type) :: h, ov
        type(status_type) :: st

        call fresh(h, "0123456789")
        call make_overlay(ov, 8_int64, 3_int64, st)
        call check(error, overlay_start(ov) == 3 .and. overlay_end(ov) == 8, "ordered")
        if (allocated(error)) return
        call move_overlay(ov, 0_int64, 100_int64, st)
        call check(error, overlay_start(ov) == 1 .and. overlay_end(ov) == 11, "clipped")
        if (allocated(error)) return
        call overlay_put(ov, "face", value_type(name="bold"), st)
        call check(error, value_eq(overlay_get(ov, "face"), value_type(name="bold")), "overlay-put")
        if (allocated(error)) return
        call delete_overlay(ov)
        call check(error, overlay_start(ov) == 0 .and. .not. is_buffer_live(overlay_buffer(ov)) .and. is_overlay(ov), &
                   "deleted")
        if (allocated(error)) return
        call check(error, value_eq(overlay_get(ov, "face"), value_type(name="bold")), "keeps its properties")
        if (allocated(error)) return
        call move_overlay(ov, 2_int64, 4_int64, st)
        call check(error, overlay_start(ov) == 2 .and. overlay_end(ov) == 4 .and. is_buffer_live(overlay_buffer(ov)), &
                   "moved back into the buffer")
        call destroy_overlay(ov)
        call check(error,.not. is_overlay(ov), "freed")
        call close_buffer(h, st)
    end subroutine test_basics

    !> Insertion at an overlay's bounds follows FRONT-ADVANCE and
    !> REAR-ADVANCE (buffer-tests.el's test-overlay-insert-*), and an empty
    !> overlay with front-advance only doesn't get inverted.
    subroutine test_insert_advance(error)
        type(error_type), allocatable, intent(out) :: error
        type(handle_type) :: h, a, b, c, e
        type(status_type) :: st

        call fresh(h, "0123456789")
        call make_overlay(a, 3_int64, 6_int64, st)
        call make_overlay(b, 3_int64, 6_int64, st, front_advance=.true., rear_advance=.true.)
        call make_overlay(c, 5_int64, 5_int64, st, front_advance=.true.)
        call make_overlay(e, 5_int64, 5_int64, st, front_advance=.true., rear_advance=.true.)
        call goto_char(3_int64)
        call insert("xx", st)
        call check(error, overlay_start(a) == 3 .and. overlay_end(a) == 8, "insert at start, no front-advance")
        if (allocated(error)) return
        call check(error, overlay_start(b) == 5 .and. overlay_end(b) == 8, "insert at start, front-advance")
        if (allocated(error)) return
        call goto_char(8_int64)
        call insert("y", st)
        call check(error, overlay_end(a) == 8, "insert at end, no rear-advance")
        if (allocated(error)) return
        call check(error, overlay_end(b) == 9, "insert at end, rear-advance")
        if (allocated(error)) return
        ! C and E are at 7 now.
        call check(error, overlay_start(c) == 7 .and. overlay_end(c) == 7, "empty overlays moved")
        if (allocated(error)) return
        call goto_char(7_int64)
        call insert("z", st)
        call check(error, overlay_start(c) == 7 .and. overlay_end(c) == 7, "empty, front-advance only: stays")
        if (allocated(error)) return
        call check(error, overlay_start(e) == 8 .and. overlay_end(e) == 8, "empty, both advance: moves")
        call destroy_overlay(a)
        call destroy_overlay(b)
        call destroy_overlay(c)
        call destroy_overlay(e)
        call close_buffer(h, st)
    end subroutine test_insert_advance

    !> Deletion contracts overlays; empty ones with `evaporate' go away.
    subroutine test_delete_text(error)
        type(error_type), allocatable, intent(out) :: error
        type(handle_type) :: h, a, b
        type(status_type) :: st

        call fresh(h, "0123456789")
        call make_overlay(a, 3_int64, 6_int64, st)
        call make_overlay(b, 4_int64, 6_int64, st)
        call overlay_put(b, "evaporate", value_type(.true.), st)
        call del_range(4_int64, 8_int64, st)
        call check(error, overlay_start(a) == 3 .and. overlay_end(a) == 4, "contracted")
        if (allocated(error)) return
        call check(error, overlay_start(b) == 0, "evaporated")
        if (allocated(error)) return
        call move_overlay(b, 2_int64, 2_int64, st)
        call check(error, overlay_start(b) == 0, "moved empty with evaporate: deleted")
        call destroy_overlay(a)
        call destroy_overlay(b)
        call close_buffer(h, st)
    end subroutine test_delete_text

    !> overlays-at (sorted by decreasing priority), overlays-in with empty
    !> overlays, next- and previous-overlay-change.
    subroutine test_queries(error)
        type(error_type), allocatable, intent(out) :: error
        type(handle_type) :: h, a, b, e
        type(handle_type), allocatable :: vec(:)
        type(status_type) :: st

        call fresh(h, "0123456789")
        call make_overlay(a, 2_int64, 6_int64, st)
        call make_overlay(b, 4_int64, 8_int64, st)
        call make_overlay(e, 9_int64, 9_int64, st)
        call overlay_put(a, "priority", value_type(10_int64), st)
        call overlays_at(5_int64, vec, sorted=.true.)
        call check(error, size(vec) == 2, "two overlays at 5")
        if (allocated(error)) return
        call check(error, vec(1)%index == a%index, "highest priority first")
        if (allocated(error)) return
        call overlays_at(9_int64, vec)
        call check(error, size(vec) == 0, "an empty overlay is not at its position")
        if (allocated(error)) return
        call overlays_in(9_int64, 9_int64, vec)
        call check(error, size(vec) == 1, "overlays-in includes it")
        if (allocated(error)) return
        call overlays_in(1_int64, 3_int64, vec)
        call check(error, size(vec) == 1, "overlays-in 1-3")
        if (allocated(error)) return
        call check(error, next_overlay_change(1_int64) == 2 .and. next_overlay_change(2_int64) == 4 .and. &
                   next_overlay_change(4_int64) == 6 .and. next_overlay_change(6_int64) == 8 .and. &
                   next_overlay_change(8_int64) == 9, "next-overlay-change")
        if (allocated(error)) return
        call check(error, previous_overlay_change(11_int64) == 9 .and. previous_overlay_change(9_int64) == 8 .and. &
                   previous_overlay_change(5_int64) == 4 .and. previous_overlay_change(2_int64) == 1, &
                   "previous-overlay-change")
        call destroy_overlay(a)
        call destroy_overlay(b)
        call destroy_overlay(e)
        call close_buffer(h, st)
    end subroutine test_queries

    !> Closing a buffer deletes its overlays.
    subroutine test_close_buffer(error)
        type(error_type), allocatable, intent(out) :: error
        type(handle_type) :: h, a
        type(status_type) :: st

        call fresh(h, "0123456789")
        call make_overlay(a, 2_int64, 6_int64, st)
        call close_buffer(h, st)
        call check(error, is_overlay(a) .and. overlay_start(a) == 0 .and. .not. is_buffer_live(overlay_buffer(a)), &
                   "no buffer after kill-buffer")
        call destroy_overlay(a)
    end subroutine test_close_buffer

    !> Redisplay merges overlays' faces in order of priority, the region
    !> (priority (nil . 100)) among them, and stops face runs at overlay
    !> boundaries.
    subroutine test_faces(error)
        type(error_type), allocatable, intent(out) :: error
        type(frame_type) :: f
        type(handle_type) :: h, a, b
        type(status_type) :: st
        integer(int64) :: bi, endpos
        integer(int32) :: id

        call init_faces()
        call init_frame_faces(f, "dumb")
        call fresh(h, "abcdefgh")
        call resolve_buffer(h, bi, st)
        call make_overlay(a, 3_int64, 6_int64, st)
        call overlay_put(a, "face", value_type(name="bold"), st)
        id = face_at_buffer_position(f, bi, 1_int64, endpos, 100_int64)
        call check(error, id == DEFAULT_FACE_ID .and. endpos == 3, "up to the overlay")
        if (allocated(error)) return
        id = face_at_buffer_position(f, bi, 3_int64, endpos, 100_int64)
        call check(error, f%faces(id)%tty_bold_p .and. endpos == 6, "the overlay's face to its end")
        if (allocated(error)) return
        ! A higher priority overlay wins over a lower one.
        call make_overlay(b, 4_int64, 6_int64, st)
        call overlay_put(b, "face", list(value_type(name=":inverse_video"), value_type(name="t")), st)
        call overlay_put(a, "face", list(value_type(name=":inverse_video"), value_type()), st)
        call overlay_put(a, "priority", value_type(10_int64), st)
        id = face_at_buffer_position(f, bi, 4_int64, endpos, 100_int64)
        call check(error,.not. f%faces(id)%tty_reverse_p, "priority 10 over 0")
        if (allocated(error)) return
        call overlay_put(a, "priority", value_type(), st)
        id = face_at_buffer_position(f, bi, 4_int64, endpos, 100_int64)
        call check(error, f%faces(id)%tty_reverse_p, "equal priority: the one not covering the other")
        if (allocated(error)) return
        ! The region, priority (nil . 100), over a priority-0 overlay with
        ! the same bounds, under a priority-1000 one.
        call delete_overlay(b)
        call move_overlay(a, 3_int64, 6_int64, st)
        id = face_at_buffer_position(f, bi, 3_int64, endpos, 100_int64, 3_int64, 6_int64)
        call check(error, f%faces(id)%tty_reverse_p, "the region over priority 0")
        if (allocated(error)) return
        call overlay_put(a, "priority", value_type(1000_int64), st)
        id = face_at_buffer_position(f, bi, 3_int64, endpos, 100_int64, 3_int64, 6_int64)
        call check(error,.not. f%faces(id)%tty_reverse_p, "priority 1000 over the region")
        call destroy_overlay(a)
        call destroy_overlay(b)
        call close_buffer(h, st)
    end subroutine test_faces

    ! ------------------------------------------------------------------
