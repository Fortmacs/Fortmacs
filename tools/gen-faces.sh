! the Free Software Foundation, either version 3 of the License, or
! (at your option) any later version.
!
! Fortmacs is distributed in the hope that it will be useful,
! but WITHOUT ANY WARRANTY; without even the implied warranty of
! MERCHANTABILITY or FITNESS FOR A PARTICULAR PURPOSE.  See the
! GNU General Public License for more details.
!
! You should have received a copy of the GNU General Public License
! along with Fortmacs.  If not, see <https://www.gnu.org/licenses/>.

!> The faces as one object, `faces`: the face named `region` is
!> `faces%region`, so the configuration writes
!> `faces%region%background = "blue"`.  Each component points at the
!> face object in the module that defines it.  Generated by
!> tools/gen-faces.sh from the face declarations in src/.
module face_table_fm
    use faces_fm, only: named_face_type
EOF
awk '{ printf "    use %s, only: %s\n", $1, $2 }' "$tmp.faces"
cat <<'EOF'
    implicit none(type, external)
    private

    public :: face_table_type, faces

    !> One component per face, pointing at the face.
    type :: face_table_type
EOF
awk '{ printf "        type(named_face_type), pointer :: %s => %s\n", $3, $2 }' "$tmp.faces"
cat <<'EOF'
    end type face_table_type

    !> The faces.
    type(face_table_type) :: faces
end module face_table_fm
EOF
} > "$tmp.f90"

if command -v fprettify >/dev/null 2>&1; then
    fprettify --config-file .fprettify.rc "$tmp.f90" 2>/dev/null
fi
awk -f tools/blank-lines.awk "$tmp.f90" >"$tmp.bl" && mv "$tmp.bl" "$tmp.f90"
mv "$tmp.f90" "$out"
