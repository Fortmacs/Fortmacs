# A face is defined as a module variable,
# `type(named_face_type), target, public :: NAME`, in the module that
# ports its defface.  This script collects those declarations from src/
# and writes a type with one pointer component per face, initialized to
# point at the face, and the `faces` variable, so the configuration
# writes `faces%region%background = "blue"` (faces, like commands, are
# a namespace of their own in Emacs).  The module is named after the
# file that declares the face.
#
# Usage: tools/gen-faces.sh [OUTPUT]
#   The default output is src/face_table_fm.f90.  It is formatted with
#   fprettify, as tools/check.sh requires.

set -eu

cd "$(dirname "$0")/.."
out=${1:-src/face_table_fm.f90}
tmp=${TMPDIR:-/tmp}/gen-faces.$$
trap 'rm -f "$tmp".*' EXIT

# "module variable face-name" lines, sorted by face name.  A face's name
# is the first argument of its `%define' call, made on the variable
# itself or through a pointer just assigned to it (`f => VAR`); it
# differs from the variable's name only where that name was taken.
find src -name '*.f90' ! -name face_table_fm.f90 ! -name docstrings_fm.f90 | sort | xargs awk '
/^[ \t]*!/ { next }
/^[ \t]*type\(named_face_type\), target, public :: [a-z0-9_]+[ \t]*$/ {
    file = FILENAME
    sub(/^.*\//, "", file)
    sub(/\.f90$/, "", file)
    print "D", file, $NF
    next
}
/^[ \t]*[a-z0-9_]+[ \t]*=>[ \t]*[a-z0-9_]+[ \t]*$/ {
    line = $0
    gsub(/[ \t]/, "", line)
    split(line, part, "=>")
    target[part[1]] = part[2]
    next
}
match($0, /[a-z0-9_]+%define\("[a-z0-9_]+"/) {
    s = substr($0, RSTART, RLENGTH)
    obj = s
    sub(/%.*/, "", obj)
    name = s
    sub(/^.*\("/, "", name)
    sub(/"$/, "", name)
    if (obj in target) obj = target[obj]
    print "N", obj, name
}' > "$tmp.raw"
awk '$1 == "N" && !($2 in name) { name[$2] = $3 }
     $1 == "D" { decl[++n] = $2 " " $3 }
     END { for (i = 1; i <= n; i++) { split(decl[i], d, " "); nm = (d[2] in name) ? name[d[2]] : d[2]; print d[1], d[2], nm } }' \
    "$tmp.raw" | sort -k3,3 > "$tmp.faces"

{
cat <<'EOF'
! face_table_fm.f90 -- the faces as one object.
! Generated by tools/gen-faces.sh; do not edit.
!
! Copyright (C) 2026 The Fortmacs authors
!
! This file is part of Fortmacs.
!
