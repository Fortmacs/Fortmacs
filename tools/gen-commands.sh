# A built-in command is defined by assigning its procedure to a component
# of `commands`, `commands%upcase_region%run => cmd_upcase_region`, in
# the module that ports it.  This script collects those components from
# src/ and writes the type with one `command_type` component per
# command, the `commands` variable, and the lookup by name.  A command's
# name is its component name with `_` written `-` (no Emacs command
# that is ported has `_` in its name).
#
# Usage: tools/gen-commands.sh [OUTPUT]
#   The default output is src/commands_fm.f90.  It is formatted with
#   fprettify, as tools/check.sh requires.

set -eu

cd "$(dirname "$0")/.."
out=${1:-src/commands_fm.f90}
tmp=${TMPDIR:-/tmp}/gen-commands.$$
trap 'rm -f "$tmp".*' EXIT

find src -name '*.f90' ! -name commands_fm.f90 ! -name docstrings_fm.f90 | sort | xargs awk '
/^[ \t]*!/ { next }
{
    line = $0
    while (match(line, /commands%[a-z0-9_]+%run[ \t]*=>/)) {
        name = substr(line, RSTART + 9, RLENGTH - 9)
        sub(/%run[ \t]*=>$/, "", name)
        print name
        line = substr(line, RSTART + RLENGTH)
    }
}' | sort -u > "$tmp.names"

{
cat <<'EOF'
! commands_fm.f90 -- the built-in commands.
! Generated by tools/gen-commands.sh; do not edit.
!
! Copyright (C) 2026 The Fortmacs authors
!
! This file is part of Fortmacs.
!
! Fortmacs is free software: you can redistribute it and/or modify
! it under the terms of the GNU General Public License as published by
! the Free Software Foundation, either version 3 of the License, or
! (at your option) any later version.
!
! Fortmacs is distributed in the hope that it will be useful,
! but WITHOUT ANY WARRANTY; without even the implied warranty of
! MERCHANTABILITY or FITNESS FOR A PARTICULAR PURPOSE.  See the
! GNU General Public License for more details.
!
! You should have received a copy of the GNU General Public License
! along with Fortmacs.  If not, see <https://www.gnu.org/licenses/>.

!> The built-in commands as one object, `commands`: the command named
!> `upcase-region` is `commands%upcase_region` (a `command_type`), so
!> the configuration writes `commands%upcase_region%disabled = .false.`.
!> Generated by tools/gen-commands.sh from the `commands%NAME%run =>`
!> assignments in src/.
module commands_fm
    use lisp_fm, only: command_type
    implicit none(type, external)
    private

    public :: command_table_type, commands, builtin_command, BUILTIN_COMMAND_NAMES

    !> One component per built-in command.
    type :: command_table_type
EOF
awk '{ print "        type(command_type) :: " $0 }' "$tmp.names"
cat <<'EOF'
    end type command_table_type

    !> The built-in commands.
    type(command_table_type), target :: commands

    !> The names of the built-in commands.
EOF
n=$(wc -l < "$tmp.names")
width=$(awk '{ if (length($0) > w) w = length($0) } END { print w + 0 }' "$tmp.names")
echo "    character(len=*), parameter :: BUILTIN_COMMAND_NAMES($n) = [character(len=$width) :: &"
awk -v n="$n" '{ name = $0; gsub(/_/, "-", name); printf "        \"%s\"%s\n", name, (NR < n ? ", &" : "]") }' "$tmp.names"
cat <<'EOF'

contains

    !> The built-in command named NAME, or null.  It gets its name the
    !> first time it is looked up.
    function builtin_command(name) result(p)
        character(len=*), intent(in) :: name
        type(command_type), pointer :: p
        p => null()
        select case (name)
EOF
awk '{ name = $0; gsub(/_/, "-", name); printf "        case (\"%s\")\n            p => commands%%%s\n", name, $0 }' "$tmp.names"
cat <<'EOF'
        case default
            return
        end select
        if (len_trim(name) /= len(name)) then
            p => null()
            return
        end if
        if (.not. allocated(p%name)) p%name = name
    end function builtin_command
end module commands_fm
EOF
} > "$tmp.f90"

if command -v fprettify >/dev/null 2>&1; then
    fprettify --config-file .fprettify.rc "$tmp.f90" 2>/dev/null
fi
mv "$tmp.f90" "$out"
