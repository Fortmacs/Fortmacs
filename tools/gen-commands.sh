# A built-in command is defined by assigning its procedure to a component
# of `commands`, `commands%upcase_region%execute => cmd_upcase_region`, in
# the module that ports it.  This script collects those components from
# src/ and writes the type with one `command_type` component per
# command, the `commands` variable, and the lookup by name.  A command's
# name is its component name with `_` written `-` (no Emacs command
# that is ported has `_` in its name).
#
# Usage: tools/gen-commands.sh [OUTPUT]
#   The default output is src/commands_mod.f90.  It is formatted with
#   fprettify, as tools/check.sh requires.

set -eu

cd "$(dirname "$0")/.."
out=${1:-src/commands_mod.f90}
tmp=${TMPDIR:-/tmp}/gen-commands.$$
trap 'rm -f "$tmp".*' EXIT

find src -name '*.f90' ! -name commands_mod.f90 ! -name docstrings_mod.f90 | sort | xargs awk '
/^[ \t]*!/ { next }
{
    line = $0
    while (match(line, /commands%[a-z0-9_]+%execute[ \t]*=>/)) {
        name = substr(line, RSTART + 9, RLENGTH - 9)
        sub(/%execute[ \t]*=>$/, "", name)
        print name
        line = substr(line, RSTART + RLENGTH)
    }
}' | sort -u > "$tmp.names"

{
cat <<'EOF'
! commands_mod.f90 -- the built-in commands.
! Generated by tools/gen-commands.sh from the `commands%NAME%execute =>` lines
! in src/; do not edit.
!
! Copyright (C) 2026 The Fortmacs authors
!
! This file is part of Fortmacs.
!
! Fortmacs is free software: you can redistribute it and/or modify
! it under the terms of the GNU General Public License as published by
! the Free Software Foundation, either version 3 of the License, or
! (at your option) any later version.
!
! Fortmacs is distributed in the hope that it will be useful,
! but WITHOUT ANY WARRANTY; without even the implied warranty of
! MERCHANTABILITY or FITNESS FOR A PARTICULAR PURPOSE.  See the
! GNU General Public License for more details.
!
! You should have received a copy of the GNU General Public License
! along with Fortmacs.  If not, see <https://www.gnu.org/licenses/>.

!> The built-in commands as one object, `commands`: the command named
!> `upcase-region` is `commands%upcase_region` (a `command_type`), so
!> the configuration writes `commands%upcase_region%disabled = .false.`.
!> Generated by tools/gen-commands.sh from the `commands%NAME%execute =>`
!> assignments in src/.
module commands_mod
    use value_mod, only: command_type
    implicit none(type, external)
    private

    public :: command_table_type, commands, builtin_command, BUILTIN_COMMAND_NAMES

    !> One component per built-in command.
    type :: command_table_type
EOF
awk '{ print "        type(command_type) :: " $0 }' "$tmp.names"
cat <<'EOF'
    end type command_table_type

    !> The built-in commands.
    type(command_table_type), target :: commands

EOF
awk '
# An array constructor of the N items ITEMS (Fortran text), with the type
# specification SPEC ("character(len=W) :: ", or ""), several items a
# line.  A list longer than 200 lines (the standard allows 255
# continuation lines a statement) is first printed as parameter arrays
# NAME_part_1, NAME_part_2, ... declared with DECL, and the constructor
# joins them.
function constructor(spec, decl, name, items, n,    nl, i, k, p, last, out, joined, line, size) {
    nl = 0
    line = ""
    for (i = 1; i <= n; i++) {
        if (line != "" && length(line) + length(items[i]) + 2 > 90) {
            ctext[++nl] = line
            cupto[nl] = i - 1
            line = ""
        }
        line = line (line == "" ? "" : ", ") items[i]
    }
    ctext[++nl] = line
    cupto[nl] = n
    p = 0
    joined = ""
    for (k = 1; k <= nl; k += 200) {
        last = (k + 199 < nl) ? k + 199 : nl
        out = "[" spec "&\n"
        for (i = k; i <= last; i++)
            out = out "        " ctext[i] (i < last ? ", &\n" : "]")
        if (nl <= 200) return out
        size = cupto[last] - (k > 1 ? cupto[k - 1] : 0)
        p++
        printf "    %s :: %s_part_%d(%d) = %s\n", decl, name, p, size, out
        joined = joined (p > 1 ? ", &\n        " : "&\n        ") name "_part_" p
    }
    print ""
    return "[" joined "]"
}

{ item[NR] = "\"" $0 "\""; if (length($0) > width) width = length($0) }
END {
    spec = sprintf("character(len=%d)", width)
    c = constructor(spec " :: ", spec ", parameter", "builtin_command_names", item, NR)
    print "    !> The names of the built-in commands."
    printf "    character(len=*), parameter :: BUILTIN_COMMAND_NAMES(%d) = %s\n", NR, c
}' "$tmp.names"
cat <<'EOF'

contains

    !> The built-in command named NAME, or null.  It gets its name the
    !> first time it is looked up.
    function builtin_command(name) result(p)
        character(len=*), intent(in) :: name
        type(command_type), pointer :: p
        p => null()
        select case (name)
EOF
awk '{ name = $0; printf "        case (\"%s\")\n            p => commands%%%s\n", name, $0 }' "$tmp.names"
cat <<'EOF'
        case default
            return
        end select
        if (len_trim(name) /= len(name)) then
            p => null()
            return
        end if
        if (len_trim(p%name) == 0) p%name = name
    end function builtin_command
end module commands_mod
EOF
} > "$tmp.f90"

if command -v fprettify >/dev/null 2>&1; then
    fprettify --config-file .fprettify.rc "$tmp.f90" 2>/dev/null
fi
awk -f tools/blank-lines.awk "$tmp.f90" >"$tmp.bl" && mv "$tmp.bl" "$tmp.f90"
mv "$tmp.f90" "$out"
