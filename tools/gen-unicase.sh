# Upstream builds its standard case table at startup from the Unicode
# simple case mappings (admin/unidata/UnicodeData.txt, through
# unidata-gen.el's uni-lowercase.el and uni-uppercase.el) in
# lisp/international/characters.el.  This script does the same at
# generation time and writes the non-ASCII entries that differ from the
# identity: the downcase table, the upcase table and the canonicalize
# table (casetab.c:set_canon), each as sorted key and value arrays.
#
# Usage: tools/gen-unicase.sh [UnicodeData.txt]
#   The default is upstream/emacs/admin/unidata/UnicodeData.txt (see
#   tools/fetch-upstream.sh).  The output replaces src/uni_case_mod.f90.

set -eu

cd "$(dirname "$0")/.."
data=${1:-upstream/emacs/admin/unidata/UnicodeData.txt}
out=src/uni_case_mod.f90

awk -F ';' '
function hex(s,    i, v) {
    # Portable: gawk does not convert "0x..." strings to numbers.
    s = toupper(s)
    v = 0
    for (i = 1; i <= length(s); i++) v = v * 16 + index("0123456789ABCDEF", substr(s, i, 1)) - 1
    return v
}
function emit(name, tbl,    keys, n, k, line, i, c) {
    n = 0
    for (k in tbl) if (k + 0 >= 128 && tbl[k] != k + 0) keys[++n] = k + 0
    sortnum(keys, n)
    what = name == "down" ? "lower case" : name == "up" ? "upper case" : "canonical (case-folded)"
    printf "    !> The number of characters (from 128) with a %s form of their own.\n", what
    printf "    integer, parameter :: %s_count = %d\n\n", name, n
    for (i = 1; i <= n; i++) vals[i] = tbl[keys[i]]
    printf "    !> The characters (from 128) with a %s form of their own, ascending.\n", what
    array(name "_keys", keys, n)
    printf "    !> Their %s forms, in the order of %s_keys.\n", what, name
    array(name "_values", vals, n)
}
function sortnum(a, n,    i, j, t, gap) {
    # Shell sort.
    for (gap = int(n / 2); gap > 0; gap = int(gap / 2))
        for (i = gap + 1; i <= n; i++) {
            t = a[i]
            for (j = i; j > gap && a[j - gap] > t; j -= gap) a[j] = a[j - gap]
            a[j] = t
        }
}
function array(name, a, n,    i, line) {
    printf "    integer(int32), parameter :: %s(%s) = [ &\n", name, (name ~ /^down/ ? "down" : name ~ /^up/ ? "up" : "canon") "_count"
    line = ""
    for (i = 1; i <= n; i++) {
        line = line sprintf("%d", a[i])
        if (i < n) line = line ", "
        if (i % 10 == 0 || i == n) {
            sub(/ $/, "", line)
            printf "        %s &\n", line
            line = ""
        }
    }
    printf "        ]\n\n"
}
function down_of(c) { return (c in down) ? down[c] : c }
function up_of(c) { return (c in up) ? up[c] : c }
{
    c = hex($1) + 0
    if ($13 != "") { m = hex($13) + 0; if (m > 127 && c >= 128) { nu++; uc[nu] = c; ucm[nu] = m } }
    if ($14 != "") { m = hex($14) + 0; if (m > 127 && c >= 128) { nl++; lc[nl] = c; lcm[nl] = m } }
}
END {
    # characters.el: first make every cased character map to itself...
    for (i = 1; i <= nu; i++) { down[uc[i]] = uc[i]; up[ucm[i]] = ucm[i] }
    for (i = 1; i <= nl; i++) { down[lcm[i]] = lcm[i]; up[lc[i]] = lc[i] }
    # ... then set the actual mappings.
    for (i = 1; i <= nu; i++) { up[uc[i]] = ucm[i]; up[ucm[i]] = ucm[i] }
    for (i = 1; i <= nl; i++) { down[lc[i]] = lcm[i]; down[lcm[i]] = lcm[i] }
    # ß upcases to ẞ in the case table (special-uppercase gives SS).
    up[223] = 7838
    # casetab.c:set_canon: canon[c] = down[up[down[c]]] for c in down.
    for (k in down) canon[k] = down_of(up_of(down[k]))
    print "! uni_case_mod.f90 -- the Unicode case tables."
    print "! Generated by tools/gen-unicase.sh from admin/unidata/UnicodeData.txt of"
    print "! GNU Emacs 31.1, as lisp/international/characters.el builds them; do not"
    print "! edit."
    print "!"
    print "! Copyright (C) 1991-2026 Unicode, Inc. (the data; see"
    print "! admin/unidata/copyright.html upstream)"
    print "! Copyright (C) 2026 The Fortmacs authors"
    print "!"
    print "! This file is part of Fortmacs."
    print "!"
    print "! Fortmacs is free software: you can redistribute it and/or modify"
    print "! it under the terms of the GNU General Public License as published by"
    print "! the Free Software Foundation, either version 3 of the License, or"
    print "! (at your option) any later version."
    print "!"
    print "! Fortmacs is distributed in the hope that it will be useful,"
    print "! but WITHOUT ANY WARRANTY; without even the implied warranty of"
    print "! MERCHANTABILITY or FITNESS FOR A PARTICULAR PURPOSE.  See the"
    print "! GNU General Public License for more details."
    print "!"
    print "! You should have received a copy of the GNU General Public License"
    print "! along with Fortmacs.  If not, see <https://www.gnu.org/licenses/>."
    print ""
    print "!> Non-ASCII entries of the standard case tables that differ from the"
    print "!> identity, sorted by key: the downcase table, the upcase table and"
    print "!> the canonicalize table.  Used by casetab_mod."
    print "module uni_case_mod"
    print "    use, intrinsic :: iso_fortran_env, only: int32"
    print "    implicit none(type, external)"
    print "    private"
    print ""
    print "    public :: down_count, down_keys, down_values, up_count, up_keys, up_values, &"
    print "              canon_count, canon_keys, canon_values"
    print ""
    emit("down", down)
    emit("up", up)
    emit("canon", canon)
    print "end module uni_case_mod"
}' "$data" > "$out.tmp"
# The last blank line before "end module" goes.
awk 'NR > 1 { if (!(prev == "" && $0 ~ /^end module/)) print prev } { prev = $0 } END { print prev }' "$out.tmp" > "$out"
rm -f "$out.tmp"
# The blank lines of CLAUDE.md.
awk -f tools/blank-lines.awk "$out" >"$out.bl" && mv "$out.bl" "$out"
echo "wrote $out"
