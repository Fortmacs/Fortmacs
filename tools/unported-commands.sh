#!/bin/sh
# unported-commands.sh -- list, per upstream Elisp file cited as ported, the
# interactive subprograms that are not yet commands of Fortmacs, into
# tools/unported-commands (the Deferred list for commands: CLAUDE.md,
# "Anything not yet ported is listed as Deferred").
#
# Copyright (C) 2026 The Fortmacs authors
#
# This file is part of Fortmacs, under the GNU GPL version 3 or later.
# Usage: tools/unported-commands.sh [OUTPUT]
#   Needs upstream/emacs (tools/fetch-upstream.sh).  The default OUTPUT
#   is tools/unported-commands; tools/check.sh --fix regenerates it and
#   tools/check.sh compares it, when upstream is present.
#
# A file is "cited as ported" when a "Port of FILE.el" appears in src/.
# Its interactive subprograms are the `(defun NAME' forms with `(interactive'
# before the next top-level form.  Each name is given its Fortran name
# (hyphens to underscores, then tools/fortran-names.sh on a probe module,
# twice to be safe) and looked up among the components of `commands'
# (src/commands_mod.f90).  The output has one line per missing command:
# FILE.el<TAB>upstream-name<TAB>fortran_name.
set -eu
cd "$(dirname "$0")/.."
out=${1:-tools/unported-commands}
up=upstream/emacs/lisp
if [ ! -d "$up" ]; then
    echo "unported-commands.sh: no upstream/emacs/lisp (run tools/fetch-upstream.sh)" >&2
    exit 2
fi
work=${TMPDIR:-/tmp}/unported-commands.$$
trap 'rm -rf "$work"' EXIT
mkdir -p "$work/src"
grep -hoE 'Port of [a-z0-9+-]+\.el' src/*.f90 | sed 's/Port of //' | sort -u >"$work/files"
: >"$work/map"
while IFS= read -r el; do
    path=$(find "$up" -name "$el" | awk '{ print length, $0 }' | sort -n | head -1 | cut -d' ' -f2-)
    [ -n "$path" ] || continue
    awk -v f="$el" '
        /^\(/ { if (look && found) print f "\t" name; look = 0; found = 0 }
        /^\(defun / { name = $2; look = 1; next }
        look && /\(interactive/ { found = 1 }
        END { if (look && found) print f "\t" name }' "$path" >>"$work/map"
done <"$work/files"
{
    echo "! probe"
    echo "module probe_mod"
    echo "    implicit none (type, external)"
    echo "contains"
    awk -F'\t' '{ u = tolower($2); gsub(/-/, "_", u); gsub(/[^a-z0-9_]/, "", u)
                  if (!(u in seen)) { seen[u] = 1; print "    subroutine " u "()"; print "    end subroutine " u } }' "$work/map"
    echo "end module probe_mod"
} >"$work/src/probe_mod.f"
tools/fortran-names.sh "$work/src/probe_mod.f" >/dev/null 2>&1 || true
tools/fortran-names.sh "$work/src/probe_mod.f" >/dev/null 2>&1 || true
grep -oE 'subroutine [a-z0-9_]+\(' "$work/src/probe_mod.f" | sed 's/subroutine //; s/(//' >"$work/renamed"
awk -F'\t' '{ u = tolower($2); gsub(/-/, "_", u); gsub(/[^a-z0-9_]/, "", u)
              if (!(u in seen)) { seen[u] = 1; print $1 "\t" $2 } }' "$work/map" >"$work/orig"
awk '/type\(command_type\) ::/ { sub(/.*:: */, ""); gsub(/&/, ""); n = split($0, a, /, */)
                                for (i = 1; i <= n; i++) if (a[i] ~ /^[a-z]/) print a[i] }' src/commands_mod.f90 | sort -u >"$work/registry"
{
    cat <<'HDR'
# unported-commands -- the interactive subprograms of the upstream Elisp files
# cited as ported that are not commands of Fortmacs yet, one per line:
# FILE.el, the upstream name, the Fortran name.  Generated by
# tools/unported-commands.sh from upstream/emacs and src/commands_mod.f90;
# this is the Deferred list for commands (CLAUDE.md).  A row goes away when
# its command is ported (tools/check.sh --fix regenerates the file when
# upstream/emacs is present).
HDR
    paste "$work/orig" "$work/renamed" | awk -F'\t' 'NR == FNR { reg[$1] = 1; next } !($3 in reg) { print $1 "\t" $2 "\t" $3 }' "$work/registry" - | sort
} >"$out"
echo "unported-commands.sh: $(grep -vc '^#' "$out") command(s) in $out"
