# Upstream generates lisp/international/charscript.el by running
# admin/unidata/blocks.awk over Blocks.txt and emoji-data.txt; loading it
# fills char-script-table, later ranges overriding earlier ones, and
# characters.el then fixes a few exceptions.  This
# script runs the same blocks.awk and turns its ranges into sorted,
# non-overlapping runs, each with a script number.
#
# Usage: tools/gen-charscript.sh [UNIDATA-DIRECTORY]
#   The default is upstream/emacs/admin/unidata (see
#   tools/fetch-upstream.sh).  The output replaces src/charscript_fm.f90.

set -eu

cd "$(dirname "$0")/.."
dir=${1:-upstream/emacs/admin/unidata}
out=src/charscript_fm.f90

{
    awk -f "$dir/blocks.awk" "$dir/Blocks.txt" "$dir/emoji-data.txt"
    # characters.el: "Fix some exceptions that blocks.awk/Blocks.txt
    # couldn't get right."
    echo "    (#x02EA #x02EB bopomofo)"
    echo "    (#xAB65 #xAB65 greek)"
    echo "    (#x16FE0 #x16FE0 tangut)"
    echo "    (#x16FE1 #x16FE1 nushu)"
} | awk '
function hex(s,    i, v) {
    sub(/^#x/, "", s)
    s = toupper(s)
    v = 0
    for (i = 1; i <= length(s); i++) v = v * 16 + index("0123456789ABCDEF", substr(s, i, 1)) - 1
    return v
}
function sortnum(a, n,    i, j, t, gap) {
    for (gap = int(n / 2); gap > 0; gap = int(gap / 2))
        for (i = gap + 1; i <= n; i++) {
            t = a[i]
            for (j = i; j > gap && a[j - gap] > t; j -= gap) a[j] = a[j - gap]
            a[j] = t
        }
}
function array(name, a, n,    i, line) {
    printf "    integer(int32), parameter :: %s(script_runs) = [ &\n", name
    line = ""
    for (i = 1; i <= n; i++) {
        line = line sprintf("%d", a[i])
        if (i < n) line = line ", "
        if (i % 10 == 0 || i == n) {
            sub(/ $/, "", line)
            printf "        %s &\n", line
            line = ""
        }
    }
    printf "        ]\n\n"
}
# Entries of the generated list: (#xSTART #xEND SCRIPT).
/^ *\(#x[0-9A-Fa-f]+ #x[0-9A-Fa-f]+ [a-z-]+\)/ {
    line = $0
    sub(/^ *\(/, "", line)
    split(line, f, /[ )]+/)
    n++
    lo[n] = hex(f[1]); hi[n] = hex(f[2]); name = f[3]
    if (!(name in id)) { id[name] = ++nnames; names[nnames] = name }
    sc[n] = id[name]
    b[++nb] = lo[n]; b[++nb] = hi[n] + 1
}
END {
    sortnum(b, nb)
    # Elementary intervals between consecutive boundaries; the last entry
    # covering one wins, as with set-char-table-range.
    nr = 0
    for (i = 1; i < nb; i++) {
        if (b[i] == b[i + 1]) continue
        s = b[i]; e = b[i + 1] - 1; w = 0
        for (k = n; k >= 1; k--) if (lo[k] <= s && e <= hi[k]) { w = sc[k]; break }
        if (w == 0) continue
        if (nr > 0 && re[nr] + 1 == s && rw[nr] == w) { re[nr] = e; continue }
        nr++; rs[nr] = s; re[nr] = e; rw[nr] = w
    }
    print "! charscript_fm.f90 -- the script of each character.  GENERATED by"
    print "! tools/gen-charscript.sh with admin/unidata/blocks.awk from Blocks.txt"
    print "! and emoji-data.txt of GNU Emacs 31.1, as lisp/international/charscript.el"
    print "! is generated.  Do not edit."
    print "!"
    print "! Copyright (C) 1991-2026 Unicode, Inc. (the data; see"
    print "! admin/unidata/copyright.html upstream)"
    print "! Copyright (C) 2015-2026 Free Software Foundation, Inc. (blocks.awk)"
    print "! Copyright (C) 2026 The Fortmacs authors"
    print "!"
    print "! This file is part of Fortmacs."
    print "!"
    print "! Fortmacs is free software: you can redistribute it and/or modify"
    print "! it under the terms of the GNU General Public License as published by"
    print "! the Free Software Foundation, either version 3 of the License, or"
    print "! (at your option) any later version."
    print "!"
    print "! Fortmacs is distributed in the hope that it will be useful,"
    print "! but WITHOUT ANY WARRANTY; without even the implied warranty of"
    print "! MERCHANTABILITY or FITNESS FOR A PARTICULAR PURPOSE.  See the"
    print "! GNU General Public License for more details."
    print "!"
    print "! You should have received a copy of the GNU General Public License"
    print "! along with Fortmacs.  If not, see <https://www.gnu.org/licenses/>."
    print ""
    print "!> char-script-table: the characters with a script, as sorted runs"
    print "!> (`script_starts` to `script_ends`, both inclusive) of script"
    print "!> `script_names(script_ids(k))`.  Used by `char_script`."
    print "module charscript_fm"
    print "    use, intrinsic :: iso_fortran_env, only: int32"
    print "    implicit none(type, external)"
    print "    private"
    print ""
    print "    public :: script_runs, script_starts, script_ends, script_ids, script_count, script_names, char_script"
    print ""
    printf "    integer, parameter :: script_runs = %d, script_count = %d\n\n", nr, nnames
    array("script_starts", rs, nr)
    array("script_ends", re, nr)
    array("script_ids", rw, nr)
    w = 1
    for (i = 1; i <= nnames; i++) if (length(names[i]) > w) w = length(names[i])
    printf "    !> The script names, numbered in order of appearance.\n"
    printf "    character(len=%d), parameter :: script_names(script_count) = [character(len=%d) :: &\n", w, w
    line = ""
    for (i = 1; i <= nnames; i++) {
        item = "\"" names[i] "\""
        if (length(line) + length(item) > 90) { printf "        %s &\n", line; line = "" }
        line = line item (i < nnames ? ", " : "")
    }
    printf "        %s]\n\n", line
    print "contains"
    print ""
    print "    !> The script number of character `c` (an index into"
    print "    !> `script_names`), or 0 if it has none.  CHAR_TABLE_REF"
    print "    !> (Vchar_script_table, c)."
    print "    pure integer function char_script(c)"
    print "        integer, intent(in) :: c"
    print "        integer :: lo, hi, mid"
    print "        char_script = 0"
    print "        lo = 1"
    print "        hi = script_runs"
    print "        do while (lo <= hi)"
    print "            mid = (lo + hi)/2"
    print "            if (c < script_starts(mid)) then"
    print "                hi = mid - 1"
    print "            else if (c > script_ends(mid)) then"
    print "                lo = mid + 1"
    print "            else"
    print "                char_script = script_ids(mid)"
    print "                return"
    print "            end if"
    print "        end do"
    print "    end function char_script"
    print "end module charscript_fm"
}' >"$out"
if command -v fprettify >/dev/null 2>&1; then
    fprettify --config-file .fprettify.rc "$out" 2>/dev/null
fi
echo "wrote $out"
