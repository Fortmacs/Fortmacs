# Upstream's lisp/term/tty-colors.el spells out `color-name-rgb-alist',
# the colors of X's rgb.txt as ("NAME" R G B) entries.  This script copies
# them, in order, into two parameter arrays: the names (blank-padded) and
# the RGB triples.
#
# Usage: tools/gen-tty-colors.sh [tty-colors.el]
#   The default is upstream/emacs/lisp/term/tty-colors.el (see
#   tools/fetch-upstream.sh).  The output replaces src/tty_colors_rgb_fm.f90.

set -eu

cd "$(dirname "$0")/.."
src=${1:-upstream/emacs/lisp/term/tty-colors.el}
out=src/tty_colors_rgb_fm.f90

awk '
/^\(defconst color-name-rgb-alist/ { inside = 1; next }
inside && /An alist of X color names/ { inside = 0; next }
inside && match($0, /\("[^"]*"[ \t]+[0-9]+[ \t]+[0-9]+[ \t]+[0-9]+\)/) {
    entry = substr($0, RSTART + 1, RLENGTH - 2)
    q = index(substr(entry, 2), "\"")
    name = substr(entry, 2, q - 1)
    rest = substr(entry, q + 2)
    split(rest, rgb, /[ \t]+/)
    k = 0
    for (i = 1; i in rgb; i++) if (rgb[i] != "") v[++k] = rgb[i]
    n++
    names[n] = name
    r[n] = v[1]; g[n] = v[2]; b[n] = v[3]
    if (length(name) > width) width = length(name)
}
END {
    print "! tty_colors_rgb_fm.f90 -- the X color names and RGB values."
    print "! Generated by tools/gen-tty-colors.sh from lisp/term/tty-colors.el of"
    print "! GNU Emacs 31.1 (color-name-rgb-alist); do not edit."
    print "!"
    print "! Copyright (C) 1999-2026 Free Software Foundation, Inc."
    print "! Copyright (C) 2026 The Fortmacs authors"
    print "!"
    print "! This file is part of Fortmacs."
    print "!"
    print "! Fortmacs is free software: you can redistribute it and/or modify"
    print "! it under the terms of the GNU General Public License as published by"
    print "! the Free Software Foundation, either version 3 of the License, or"
    print "! (at your option) any later version."
    print "!"
    print "! Fortmacs is distributed in the hope that it will be useful,"
    print "! but WITHOUT ANY WARRANTY; without even the implied warranty of"
    print "! MERCHANTABILITY or FITNESS FOR A PARTICULAR PURPOSE.  See the"
    print "! GNU General Public License for more details."
    print "!"
    print "! You should have received a copy of the GNU General Public License"
    print "! along with Fortmacs.  If not, see <https://www.gnu.org/licenses/>."
    print ""
    print "!> X color names and associated 16-bit RGB values: entry I is named"
    print "!> `color_names(I)'"'"' (blank-padded) and has the red, green and blue values"
    print "!> `color_rgbs(:, I)'"'"', in the order of upstream'"'"'s table.  Used by"
    print "!> tty_colors_fm.  Port of term/tty-colors.el:color-name-rgb-alist."
    print "module tty_colors_rgb_fm"
    print "    implicit none(type, external)"
    print "    private"
    print ""
    print "    public :: color_name_count, color_name_width, color_names, color_rgbs"
    print ""
    printf "    !> The number of entries.\n"
    printf "    integer, parameter :: color_name_count = %d\n", n
    printf "    !> The length of the longest name.\n"
    printf "    integer, parameter :: color_name_width = %d\n\n", width
    print "    !> The color names, blank-padded to `color_name_width'"'"'."
    print "    character(len=color_name_width), parameter :: color_names(color_name_count) = [character(len=color_name_width) :: &"
    for (i = 1; i <= n; i++) {
        printf "        \"%s\"%s\n", names[i], (i < n) ? ", &" : " &"
    }
    print "        ]"
    print ""
    print "    !> The red, green and blue values (0..65535) of each name."
    print "    integer, parameter :: color_rgbs(3, color_name_count) = reshape([ &"
    for (i = 1; i <= n; i++) {
        printf "        %d, %d, %d%s\n", r[i], g[i], b[i], (i < n) ? ", &" : " &"
    }
    print "        ], [3, color_name_count])"
    print "end module tty_colors_rgb_fm"
}' "$src" >"$out"
if command -v fprettify >/dev/null 2>&1; then
    fprettify --config-file .fprettify.rc "$out" 2>/dev/null
fi
# The blank lines of CLAUDE.md.
awk -f tools/blank-lines.awk "$out" >"$out.bl" && mv "$out.bl" "$out"
echo "wrote $out"
