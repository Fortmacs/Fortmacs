# Upstream's unidata-gen.el writes the general-category property table
# Upstream's unidata-gen.el writes the bidi-class property table
# (lisp/international/uni-bidi.el) from UnicodeData.txt, giving the code
# points UnicodeData.txt leaves out the defaults of its bidi-class entry
# (those of DerivedBidiClass.txt for some blocks, else L); the mirroring
# table (uni-mirrored.el) from BidiMirroring.txt, and the bracket-type
# table (uni-brackets.el) from BidiBrackets.txt.  This script writes them
# for bidi.c (bidi_mod): the bidi classes as sorted runs of characters of
# one class, the mirrored pairs, and the opening and closing brackets.
#
# Usage: tools/gen-unibidi.sh [UNIDATA-DIRECTORY]
#   The default is upstream/emacs/admin/unidata (see
#   tools/fetch-upstream.sh).  The output replaces src/uni_bidi_mod.f90.

set -eu

cd "$(dirname "$0")/.."
dir=${1:-upstream/emacs/admin/unidata}
out=src/uni_bidi_mod.f90

awk -F ';' '
function hex(s,    i, v) {
    s = toupper(s)
    gsub(/[ \t]/, "", s)
    v = 0
    for (i = 1; i <= length(s); i++) v = v * 16 + index("0123456789ABCDEF", substr(s, i, 1)) - 1
    return v
}
function array(name, count, a, n,    i, line) {
    printf "    integer(int32), parameter :: %s(%s) = [ &\n", name, count
    line = ""
    for (i = 1; i <= n; i++) {
        line = line sprintf("%d", a[i])
        if (i < n) line = line ", "
        if (i % 10 == 0 || i == n) {
            sub(/ $/, "", line)
            printf "        %s &\n", line
            line = ""
        }
    }
    printf "        ]\n\n"
}
BEGIN {
    split("L R EN AN BN B AL LRE LRO RLE RLO PDF LRI RLI FSI PDI ES ET CS NSM S WS ON", names, " ")
    for (i = 1; i <= 23; i++) code[names[i]] = i
    # unidata-gen.el: the defaults of bidi-class for unlisted code points.
    nd = split("0600 07BF AL 0860 08FF AL FB50 FDCF AL FDF0 FDFF AL FE70 FEFF AL 10D00 10D3F AL " \
               "10EC0 10EFF AL 10F30 10F6F AL 1EC70 1ECBF AL 1ED00 1ED4F AL 1EE00 1EEFF AL " \
               "0590 05FF R 07C0 085F R FB1D FB4F R 10800 10CFF R 10D40 10EBF R 10F00 10F2F R " \
               "10F70 10FFF R 1E800 1EC6F R 1ECC0 1ECFF R 1ED50 1EDFF R 1EF00 1EFFF R 20A0 20CF ET", d, " ")
    for (i = 1; i <= nd; i += 3) {
        nr++; ds[nr] = hex(d[i]); de[nr] = hex(d[i + 1]); dc[nr] = code[d[i + 2]]
    }
}
FILENAME ~ /UnicodeData/ {
    c = hex($1)
    if ($2 ~ /, First>$/) { first = c; next }
    if ($2 ~ /, Last>$/) { nrng++; rs[nrng] = first; re[nrng] = c; rc[nrng] = code[$5]; next }
    cls[c] = code[$5]
    next
}
FILENAME ~ /BidiMirroring/ {
    sub(/#.*/, "")
    if (NF < 2) next
    nm++; mf[nm] = hex($1); mt[nm] = hex($2)
    next
}
FILENAME ~ /BidiBrackets/ {
    sub(/#.*/, "")
    if (NF < 3) next
    t = $3; gsub(/[ \t]/, "", t)
    if (t == "o") { no++; bo[no] = hex($1) } else { nc++; bc[nc] = hex($1) }
    next
}
END {
    for (c = 0; c <= 1114111; c++) {
        if (c in cls) k = cls[c]
        else {
            k = 0
            for (i = 1; i <= nrng && !k; i++) if (rs[i] <= c && c <= re[i]) k = rc[i]
            for (i = 1; i <= nr && !k; i++) if (ds[i] <= c && c <= de[i]) k = dc[i]
            if (!k) k = code["L"]
        }
        if (g > 0 && gc[g] == k) ge[g] = c
        else { g++; gs[g] = c; ge[g] = c; gc[g] = k }
    }
    print "! uni_bidi_mod.f90 -- Unicode bidi classes, mirrored characters and brackets."
    print "! Generated by tools/gen-unibidi.sh from admin/unidata/UnicodeData.txt,"
    print "! BidiMirroring.txt and BidiBrackets.txt of GNU Emacs 31.1, the sources of"
    print "! lisp/international/uni-bidi.el, uni-mirrored.el and uni-brackets.el; do"
    print "! not edit."
    print "!"
    print "! Copyright (C) 1991-2026 Unicode, Inc. (the data; see"
    print "! admin/unidata/copyright.html upstream)"
    print "! Copyright (C) 2026 The Fortmacs authors"
    print "!"
    print "! This file is part of Fortmacs."
    print "!"
    print "! Fortmacs is free software: you can redistribute it and/or modify"
    print "! it under the terms of the GNU General Public License as published by"
    print "! the Free Software Foundation, either version 3 of the License, or"
    print "! (at your option) any later version."
    print "!"
    print "! Fortmacs is distributed in the hope that it will be useful,"
    print "! but WITHOUT ANY WARRANTY; without even the implied warranty of"
    print "! MERCHANTABILITY or FITNESS FOR A PARTICULAR PURPOSE.  See the"
    print "! GNU General Public License for more details."
    print "!"
    print "! You should have received a copy of the GNU General Public License"
    print "! along with Fortmacs.  If not, see <https://www.gnu.org/licenses/>."
    print ""
    print "!> The bidi class of every code point up to U+10FFFF as sorted runs"
    print "!> from `bidi_starts` to `bidi_ends` (inclusive) of class `bidi_codes`"
    print "!> (dispextern.h bidi_type_t: 1 L, 2 R, 3 EN, ... 23 ON); the mirrored"
    print "!> characters, `mirror_from` to `mirror_to`, sorted; the opening and"
    print "!> the closing paired brackets, sorted.  Used by bidi_mod."
    print "module uni_bidi_mod"
    print "    use, intrinsic :: iso_fortran_env, only: int32"
    print "    implicit none(type, external)"
    print "    private"
    print ""
    print "    public :: bidi_runs, bidi_starts, bidi_ends, bidi_codes, mirror_count, mirror_from, mirror_to, &"
    print "              open_bracket_count, open_brackets, close_bracket_count, close_brackets"
    print ""
    print "    !> The numbers of runs of one bidi class, of mirrored characters and of"
    print "    !> opening and closing brackets."
    printf "    integer, parameter :: bidi_runs = %d, mirror_count = %d, open_bracket_count = %d, &\n", g, nm, no
    printf "                          close_bracket_count = %d\n\n", nc
    print "    !> The first characters of the runs of one bidi class."
    array("bidi_starts", "bidi_runs", gs, g)
    print "    !> The last characters of the runs of one bidi class."
    array("bidi_ends", "bidi_runs", ge, g)
    print "    !> The bidi class of each run."
    array("bidi_codes", "bidi_runs", gc, g)
    print "    !> The mirrored characters (BidiMirroring.txt)."
    array("mirror_from", "mirror_count", mf, nm)
    print "    !> The mirror image of each of `mirror_from`."
    array("mirror_to", "mirror_count", mt, nm)
    print "    !> The opening paired brackets (BidiBrackets.txt)."
    array("open_brackets", "open_bracket_count", bo, no)
    print "    !> The closing paired brackets."
    array("close_brackets", "close_bracket_count", bc, nc)
    print "end module uni_bidi_mod"
}' "$dir/UnicodeData.txt" "$dir/BidiMirroring.txt" "$dir/BidiBrackets.txt" >"$out"
if command -v fprettify >/dev/null 2>&1; then
    fprettify --config-file .fprettify.rc "$out" 2>/dev/null
fi
# The blank lines of CLAUDE.md.
awk -f tools/blank-lines.awk "$out" >"$out.bl" && mv "$out.bl" "$out"
echo "wrote $out"
