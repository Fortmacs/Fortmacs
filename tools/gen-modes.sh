! You should have received a copy of the GNU General Public License
! along with Fortmacs.  If not, see <https://www.gnu.org/licenses/>.

!> The built-in modes as two objects: the major mode `text-mode` is
!> `major_modes%text_mode` (a `major_mode_type`), the minor mode
!> `auto-fill-mode` is `minor_modes%auto_fill_mode` (a
!> `minor_mode_type`), so the configuration writes
!> `call major_modes%text_mode%hook%add(turn_on_auto_fill)`.
!> Generated by tools/gen-modes.sh from the `%define(` calls in src/.
module modes_fm
    use derived_fm, only: major_mode_type
    use easy_mmode_fm, only: minor_mode_type
    implicit none(type, external)
    private

    public :: major_mode_table_type, minor_mode_table_type, major_modes, minor_modes

    !> One component per built-in major mode.
    type :: major_mode_table_type
EOF
awk '{ print "        type(major_mode_type) :: " $0 }' "$tmp.major"
cat <<'EOF'
    end type major_mode_table_type

    !> One component per built-in minor mode.
    type :: minor_mode_table_type
EOF
awk '{ print "        type(minor_mode_type) :: " $0 }' "$tmp.minor"
cat <<'EOF'
    end type minor_mode_table_type

    !> The built-in major modes.
    type(major_mode_table_type), target :: major_modes

    !> The built-in minor modes.
    type(minor_mode_table_type), target :: minor_modes
end module modes_fm
EOF
} > "$tmp.f90"

if command -v fprettify >/dev/null 2>&1; then
    fprettify --config-file .fprettify.rc "$tmp.f90" 2>/dev/null
fi
awk -f tools/blank-lines.awk "$tmp.f90" >"$tmp.bl" && mv "$tmp.bl" "$tmp.f90"
mv "$tmp.f90" "$out"
