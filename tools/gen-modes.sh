# A built-in mode is defined in the module that ports it, by calling
# `major_modes%NAME%define(...)` or `minor_modes%NAME%define(...)`.  This
# script collects those components from src/ and writes the two types
# with one component per mode, and the two variables.
#
# Usage: tools/gen-modes.sh [OUTPUT]
#   The default output is src/modes_fm.f90.  It is formatted with
#   fprettify, as tools/check.sh requires.

set -eu

cd "$(dirname "$0")/.."
out=${1:-src/modes_fm.f90}
tmp=${TMPDIR:-/tmp}/gen-modes.$$
trap 'rm -f "$tmp".*' EXIT

collect() {
    find src -name '*.f90' ! -name modes_fm.f90 ! -name docstrings_fm.f90 | sort | xargs awk -v kind="$1" '
/^[ \t]*!/ { next }
{
    line = $0
    pat = kind "%[a-z0-9_]+%define[ \t]*\\("
    while (match(line, pat)) {
        name = substr(line, RSTART + length(kind) + 1, RLENGTH - length(kind) - 1)
        sub(/%define.*$/, "", name)
        print name
        line = substr(line, RSTART + RLENGTH)
    }
}' | sort -u
}
collect major_modes > "$tmp.major"
collect minor_modes > "$tmp.minor"

{
cat <<'EOF'
! modes_fm.f90 -- the built-in major and minor modes.
! Generated by tools/gen-modes.sh; do not edit.
!
! Copyright (C) 2026 The Fortmacs authors
!
! This file is part of Fortmacs.
!
! Fortmacs is free software: you can redistribute it and/or modify
! it under the terms of the GNU General Public License as published by
