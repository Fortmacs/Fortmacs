!> The files Fortmacs saves its state in between sessions (savehist's
!> minibuffer histories, saveplace's places) are written in Fortran
!> namelist syntax, where upstream writes Lisp data:
!>
!>     ! Minibuffer history file, automatically generated by `savehist'.
!>     &savehist
!>      savehist_minibuffer_history_variables(1:2) = "file_name_history", "extended_command_history",
!>      file_name_history(1:2) = "~/src/my-notes.txt", "~/notes.txt",
!>     /
!>
!> A file holds groups (`&NAME' ... `/'), each a list of objects
!> `DESIGNATOR = VALUE, VALUE, ...' where a designator is a name with an
!> optional subscript and component (`place(2)%file') and the values are
!> character constants (in either quote, the quote doubled inside),
!> integers and logicals (.true. or .false.; .t., .f., T and F are read
!> too).  `!' starts a comment outside a character constant.  An array
!> is written with its section, `name(1:n) = ...', so it reads back as
!> an array even with one element.
!>
!> The syntax is read and written here rather than by the `nml='
!> specifier, which needs every object declared at compile time with a
!> fixed length: histories hold any number of strings of any length,
!> and the variables savehist saves are named at run time.  Unlike a
!> namelist READ, a line break inside a character constant is kept.
!> (Ours: not a port.)
module namelist_fm
    use, intrinsic :: iso_fortran_env, only: int64
    use error_fm, only: status_type, set_error, FM_INVALID_READ_SYNTAX
    implicit none(type, external)
    private

    public :: read_namelist, namelist_text, namelist_string_literal

    !> Kinds of namelist value.
    integer, parameter, public :: NAMELIST_STRING = 1, NAMELIST_INTEGER = 2, NAMELIST_LOGICAL = 3

    !> One value: a character constant, an integer or a logical.
    type, public :: namelist_value_type
        integer :: kind = NAMELIST_STRING
        character(len=:), allocatable :: string
        integer(int64) :: integer = 0
        logical :: logical = .false.
    end type namelist_value_type

    !> One object of a group: `NAME(LOWER:UPPER)%COMPONENT = VALUES'
    !> (`subscripted' says whether the name has a subscript; UPPER is
    !> LOWER for a single index; COMPONENT is empty for none).
    type, public :: namelist_item_type
        character(len=:), allocatable :: name, component
        logical :: subscripted = .false.
        integer(int64) :: lower = 0, upper = 0
        type(namelist_value_type), allocatable :: values(:)
    contains
        !> Append a character constant to the values.
        procedure :: add_string => item_add_string
        !> Append an integer to the values.
        procedure :: add_integer => item_add_integer
        !> Append a logical to the values.
        procedure :: add_logical => item_add_logical
    end type namelist_item_type

    !> A group `&NAME ... /'.
    type, public :: namelist_group_type
        character(len=:), allocatable :: name
        type(namelist_item_type), allocatable :: items(:)
    contains
        !> Append an object.
        procedure :: add => group_add
    end type namelist_group_type

contains

    ! ------------------------------------------------------------------
    ! Building groups
    ! ------------------------------------------------------------------

    subroutine item_add_value(self, v)
        class(namelist_item_type), intent(inout) :: self
        type(namelist_value_type), intent(in) :: v
        type(namelist_value_type), allocatable :: grown(:)
        integer :: k, n

        n = 0
        if (allocated(self%values)) n = size(self%values)
        allocate (grown(n + 1))

        do k = 1, n
            grown(k) = self%values(k)
        end do

        grown(n + 1) = v
        call move_alloc(grown, self%values)
    end subroutine item_add_value

    subroutine item_add_string(self, string)
        class(namelist_item_type), intent(inout) :: self
        character(len=*), intent(in) :: string
        type(namelist_value_type) :: v

        v%kind = NAMELIST_STRING
        v%string = string
        call item_add_value(self, v)
    end subroutine item_add_string

    subroutine item_add_integer(self, n)
        class(namelist_item_type), intent(inout) :: self
        integer(int64), intent(in) :: n
        type(namelist_value_type) :: v

        v%kind = NAMELIST_INTEGER
        v%integer = n
        call item_add_value(self, v)
    end subroutine item_add_integer

    subroutine item_add_logical(self, b)
        class(namelist_item_type), intent(inout) :: self
        logical, intent(in) :: b
        type(namelist_value_type) :: v

        v%kind = NAMELIST_LOGICAL
        v%logical = b
        call item_add_value(self, v)
    end subroutine item_add_logical

    subroutine group_add(self, item)
        class(namelist_group_type), intent(inout) :: self
        type(namelist_item_type), intent(in) :: item
        type(namelist_item_type), allocatable :: grown(:)
        integer :: k, n

        n = 0
        if (allocated(self%items)) n = size(self%items)
        allocate (grown(n + 1))

        do k = 1, n
            grown(k) = self%items(k)
        end do

        grown(n + 1) = item
        call move_alloc(grown, self%items)
    end subroutine group_add

    ! ------------------------------------------------------------------
    ! Writing
    ! ------------------------------------------------------------------

    !> TEXT as a character constant: in double quotes, each double quote
    !> doubled.
    pure function namelist_string_literal(text) result(s)
        character(len=*), intent(in) :: text
        character(len=:), allocatable :: s
        integer :: k

        s = '"'

        do k = 1, len(text)
            if (text(k:k) == '"') then
                s = s//'""'
            else
                s = s//text(k:k)
            end if
        end do

        s = s//'"'
    end function namelist_string_literal

    !> GROUP in namelist syntax, one object to a line, ending in a newline.
    function namelist_text(group) result(text)
        type(namelist_group_type), intent(in) :: group
        character(len=:), allocatable :: text
        character(len=24) :: buf
        integer :: k, j

        text = "&"//group%name//achar(10)

        if (allocated(group%items)) then
            do k = 1, size(group%items)
                associate (it => group%items(k))
                    text = text//" "//it%name

                    if (it%subscripted) then
                        write (buf, "(i0)") it%lower
                        text = text//"("//trim(buf)

                        if (it%upper /= it%lower) then
                            write (buf, "(i0)") it%upper
                            text = text//":"//trim(buf)
                        end if

                        text = text//")"
                    end if

                    if (allocated(it%component)) then
                        if (len(it%component) > 0) text = text//"%"//it%component
                    end if

                    text = text//" ="

                    if (allocated(it%values)) then
                        do j = 1, size(it%values)
                            if (j > 1) text = text//","
                            text = text//" "//value_text(it%values(j))
                        end do
                    end if

                    text = text//","//achar(10)
                end associate
            end do
        end if

        text = text//"/"//achar(10)

    contains

        function value_text(v) result(s)
            type(namelist_value_type), intent(in) :: v
            character(len=:), allocatable :: s

            select case (v%kind)
            case (NAMELIST_INTEGER)
                write (buf, "(i0)") v%integer
                s = trim(buf)
            case (NAMELIST_LOGICAL)
                if (v%logical) then
                    s = ".true."
                else
                    s = ".false."
                end if
            case default
                s = namelist_string_literal(v%string)
            end select
        end function value_text
    end function namelist_text

    ! ------------------------------------------------------------------
    ! Reading
    ! ------------------------------------------------------------------

    !> The groups of TEXT, in order.  A syntax error is an
    !> invalid_read_syntax error naming the line.
    subroutine read_namelist(text, groups, status)
        character(len=*), intent(in) :: text
        type(namelist_group_type), allocatable, intent(out) :: groups(:)
        type(status_type), intent(out) :: status
        type(namelist_group_type), allocatable :: grown(:)
        type(namelist_group_type) :: group
        type(namelist_item_type) :: item
        integer :: pos, k, n

        allocate (groups(0))
        pos = 1

        do
            call skip_blanks()
            if (pos > len(text)) return

            if (text(pos:pos) /= "&") then
                call syntax_error()
                return
            end if

            pos = pos + 1
            group = namelist_group_type()
            call read_name(group%name)

            if (len(group%name) == 0) then
                call syntax_error()
                return
            end if

            do
                call skip_blanks()

                if (pos > len(text)) then
                    call syntax_error()
                    return
                end if

                if (text(pos:pos) == "/") then
                    pos = pos + 1
                    exit
                end if

                call read_item(item)
                if (.not. status%ok()) return
                call group%add(item)
            end do

            n = size(groups)
            allocate (grown(n + 1))

            do k = 1, n
                grown(k) = groups(k)
            end do

            grown(n + 1) = group
            call move_alloc(grown, groups)
        end do

    contains

        !> Skip blanks, newlines, commas and comments.
        subroutine skip_blanks()
            do while (pos <= len(text))
                select case (text(pos:pos))
                case (" ", achar(9), achar(10), achar(13), ",")
                    pos = pos + 1
                case ("!")
                    do while (pos <= len(text))
                        if (text(pos:pos) == achar(10)) exit
                        pos = pos + 1
                    end do
                case default
                    return
                end select
            end do
        end subroutine skip_blanks

        logical function name_char(c)
            character(len=1), intent(in) :: c

            name_char = (c >= "a" .and. c <= "z") .or. (c >= "A" .and. c <= "Z") .or. &
                        (c >= "0" .and. c <= "9") .or. c == "_"
        end function name_char

        subroutine read_name(name)
            character(len=:), allocatable, intent(out) :: name
            integer :: start

            start = pos

            do while (pos <= len(text))
                if (.not. name_char(text(pos:pos))) exit
                pos = pos + 1
            end do

            name = text(start:pos - 1)
        end subroutine read_name

        subroutine read_integer(n, ok)
            integer(int64), intent(out) :: n
            logical, intent(out) :: ok
            integer :: start, ios

            start = pos

            if (pos <= len(text)) then
                if (text(pos:pos) == "-" .or. text(pos:pos) == "+") pos = pos + 1
            end if

            do while (pos <= len(text))
                if (text(pos:pos) < "0" .or. text(pos:pos) > "9") exit
                pos = pos + 1
            end do

            n = 0
            ok = pos > start
            if (ok) read (text(start:pos - 1), *, iostat=ios) n
            if (ok) ok = ios == 0
        end subroutine read_integer

        !> `DESIGNATOR = VALUE, ...'
        subroutine read_item(it)
            type(namelist_item_type), intent(out) :: it
            type(namelist_value_type) :: v
            logical :: ok, more

            call read_name(it%name)

            if (len(it%name) == 0) then
                call syntax_error()
                return
            end if

            it%component = ""

            if (pos <= len(text)) then
                if (text(pos:pos) == "(") then
                    pos = pos + 1
                    it%subscripted = .true.
                    call read_integer(it%lower, ok)

                    if (.not. ok) then
                        call syntax_error()
                        return
                    end if

                    it%upper = it%lower

                    if (pos <= len(text)) then
                        if (text(pos:pos) == ":") then
                            pos = pos + 1
                            call read_integer(it%upper, ok)

                            if (.not. ok) then
                                call syntax_error()
                                return
                            end if
                        end if
                    end if

                    if (.not. at(")")) then
                        call syntax_error()
                        return
                    end if

                    pos = pos + 1
                end if
            end if

            if (at("%")) then
                pos = pos + 1
                call read_name(it%component)
            end if

            call skip_spaces()

            if (.not. at("=")) then
                call syntax_error()
                return
            end if

            pos = pos + 1
            allocate (it%values(0))

            do
                call skip_blanks()
                if (pos > len(text)) return
                call read_value(v, more)
                if (.not. status%ok()) return
                if (.not. more) return
                call item_add_value(it, v)
            end do
        end subroutine read_item

        subroutine skip_spaces()
            do while (pos <= len(text))
                if (text(pos:pos) /= " " .and. text(pos:pos) /= achar(9)) exit
                pos = pos + 1
            end do
        end subroutine skip_spaces

        logical function at(c)
            character(len=1), intent(in) :: c

            at = .false.
            if (pos <= len(text)) at = text(pos:pos) == c
        end function at

        !> The value at POS; MORE is false (and nothing is read) at the
        !> `/' ending the group or at the next object's designator.
        subroutine read_value(v, more)
            type(namelist_value_type), intent(out) :: v
            logical, intent(out) :: more
            character(len=1) :: q
            integer :: save
            logical :: ok

            more = .true.

            select case (text(pos:pos))
            case ("/")
                more = .false.
            case ('"', "'")
                q = text(pos:pos)
                pos = pos + 1
                v%kind = NAMELIST_STRING
                v%string = ""

                do
                    if (pos > len(text)) then
                        call syntax_error()
                        return
                    end if

                    if (text(pos:pos) == q) then
                        if (pos < len(text)) then
                            if (text(pos + 1:pos + 1) == q) then
                                v%string = v%string//q
                                pos = pos + 2
                                cycle
                            end if
                        end if

                        pos = pos + 1
                        exit
                    end if

                    v%string = v%string//text(pos:pos)
                    pos = pos + 1
                end do
            case (".")
                v%kind = NAMELIST_LOGICAL

                if (starts(".true.")) then
                    v%logical = .true.
                    pos = pos + 6
                else if (starts(".false.")) then
                    pos = pos + 7
                else if (starts(".t.")) then
                    v%logical = .true.
                    pos = pos + 3
                else if (starts(".f.")) then
                    pos = pos + 3
                else
                    call syntax_error()
                end if
            case ("-", "+", "0":"9")
                v%kind = NAMELIST_INTEGER
                call read_integer(v%integer, ok)
                if (.not. ok) call syntax_error()
            case ("T", "F", "t", "f")
                ! A logical, unless it begins the next object's name.
                save = pos
                pos = pos + 1

                if (pos <= len(text)) then
                    if (name_char(text(pos:pos))) then
                        pos = save
                        more = .false.
                        return
                    end if
                end if

                call skip_spaces()

                if (at("=") .or. at("(") .or. at("%")) then
                    pos = save
                    more = .false.
                    return
                end if

                v%kind = NAMELIST_LOGICAL
                v%logical = text(save:save) == "T" .or. text(save:save) == "t"
            case default
                if (name_char(text(pos:pos))) then
                    more = .false.
                else
                    call syntax_error()
                end if
            end select
        end subroutine read_value

        logical function starts(word)
            character(len=*), intent(in) :: word
            integer :: k

            starts = pos + len(word) - 1 <= len(text)
            if (.not. starts) return

            do k = 1, len(word)
                if (lower(text(pos + k - 1:pos + k - 1)) /= word(k:k)) then
                    starts = .false.
                    return
                end if
            end do
        end function starts

        pure character(len=1) function lower(c)
            character(len=1), intent(in) :: c

            lower = c
            if (c >= "A" .and. c <= "Z") lower = achar(iachar(c) + 32)
        end function lower

        subroutine syntax_error()
            character(len=12) :: buf
            integer :: line, k

            line = 1

            do k = 1, min(pos, len(text)) - 1
                if (text(k:k) == achar(10)) line = line + 1
            end do

            write (buf, "(i0)") line
            call set_error(status, FM_INVALID_READ_SYNTAX, "namelist syntax, line "//trim(buf))
        end subroutine syntax_error
    end subroutine read_namelist
end module namelist_fm
