    ! Check DIMENSION, CHARS and FINAL_CHAR; true if they are valid.  Port
    ! of charset.c:check_iso_charset_parameter.
    logical function check_iso_charset_parameter(dimension, chars, final_char, status) result(ok)
        integer, intent(in) :: dimension, chars, final_char
        type(status_type), intent(inout) :: status
        character(len=12) :: buf

        ok = .false.

        if (dimension < 1 .or. dimension > 3) then
            write (buf, "(i0)") dimension
            call set_error(status, FM_ARGS_OUT_OF_RANGE, "1, 3, "//trim(buf))
            return
        end if

        if (chars /= 94 .and. chars /= 96) then
            write (buf, "(i0)") chars
            call set_error(status, FM_GENERIC_ERROR, "Invalid CHARS: "//trim(buf))
            return
        end if

        if (final_char < iachar("0") .or. final_char > 127) then
            write (buf, "(i0)") final_char
            call set_error(status, FM_ARGS_OUT_OF_RANGE, "48, 127, "//trim(buf))
            return
        end if

        ok = .true.
    end function check_iso_charset_parameter

    !> An unused final character for an ISO charset of DIMENSION and CHARS
