    !> The first of the charsets RESTRICTION that contains C ("" for none).
    !> Port of charset.c:Fchar_charset with a list as RESTRICTION (a
    !> coding system as RESTRICTION waits for the charset coding systems).
    function char_charset_in(c, restriction, status) result(name)
        integer, intent(in) :: c
        character(len=*), intent(in) :: restriction(:)
        type(status_type), intent(out) :: status
        character(len=:), allocatable :: name
        integer :: i, id

        call syms_of_charset()
        name = ""

        do i = 1, size(restriction)
            id = check_charset(trim(restriction(i)), status)
            if (id == 0) return

            if (encode_char_id(id, c, status) /= charsets(id)%invalid_code) then
                name = trim(restriction(i))
                return
            end if

            if (status%code /= FM_OK) return
        end do
    end function char_charset_in

    !> The charset of C by the current priority of charsets, with the
    !> position code of each of its dimensions in CODES.  Port of
    !> charset.c:Fsplit_char.
    subroutine split_char(c, charset, codes, status)
        integer, intent(in) :: c
        character(len=:), allocatable, intent(out) :: charset
        integer, allocatable, intent(out) :: codes(:)
        type(status_type), intent(out) :: status
        integer(int64) :: code
        integer :: id, d

        call syms_of_charset()
        charset = ""
        allocate (codes(0))

        if (c < 0 .or. c > MAX_CHAR) then
            call set_error(status, FM_WRONG_TYPE_ARGUMENT, "characterp")
            return
        end if

        id = char_charset_macro(c, code, status)
        if (id == 0 .or. status%code /= FM_OK) return
        charset = charsets(id)%name
        deallocate (codes)
        allocate (codes(charsets(id)%dimension))

        do d = charsets(id)%dimension, 1, -1
            codes(d) = int(iand(code, 255_int64))
            code = ishft(code, -8)
        end do
    end subroutine split_char

    !> The charset of the character at POS in the current buffer ("" when
    !> POS is outside the accessible part).  Port of
    !> charset.c:Fcharset_after.
    function charset_after(pos) result(name)
        integer(int64), intent(in) :: pos
        character(len=:), allocatable :: name
        character(len=:), allocatable :: bytes
        type(status_type) :: status
        integer(int64) :: code
        integer :: c, length, id

        call syms_of_charset()
        name = ""

        associate (b => buffers(cur))
            if (pos < b%begv .or. pos >= b%zv) return
            bytes = buf_bytes(b, char_to_byte(pos), char_to_byte(pos + 1))
        end associate

        if (.not. buffers(cur)%multibyte) then
            c = iachar(bytes(1:1))
        else
            call string_char_and_length(bytes, 1_int64, c, length)
        end if

        id = char_charset_macro(c, code, status)
        if (id /= 0) name = charsets(id)%name
    end function charset_after

