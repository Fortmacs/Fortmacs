        character(len=*), intent(in) :: names(:)
        type(status_type), intent(out) :: status
        integer, allocatable :: head(:), rest(:), list_2022(:), list_mule(:)
        integer :: i, id, nhead

        call syms_of_charset()
        allocate (head(size(names)))
        nhead = 0
        rest = ordered(1:nordered)

        do i = 1, size(names)
            id = check_charset(trim(names(i)), status)
            if (id == 0) return

            if (any(rest == id)) then
                rest = pack(rest, rest /= id)
                nhead = nhead + 1
                head(nhead) = id
            end if
        end do

        ordered(1:nordered) = [head(1:nhead), rest]

        if (size(rest) > 0) then
            non_preferred_head = nhead + 1
        else
            non_preferred_head = 0
        end if

        charset_unibyte = -1
        allocate (list_2022(0), list_mule(0))

        do i = 1, nordered
            id = ordered(i)
            if (any(iso_2022_list == id)) list_2022 = [list_2022, id]
            if (any(emacs_mule_list == id)) list_mule = [list_mule, id]

            if (charset_unibyte < 0) then
                if (charsets(id)%dimension == 1 .and. charsets(id)%ascii_compatible_p &
                    .and. charsets(id)%max_char >= 128) charset_unibyte = id
            end if
        end do

        iso_2022_list = list_2022
        emacs_mule_list = list_mule
        if (charset_unibyte < 0) charset_unibyte = charset_iso_8859_1
    end subroutine set_charset_priority

    !> CHARSETS sorted by priority.  Port of charset.c:Fsort_charsets.
    function sort_charsets(names, status) result(sorted)
        character(len=*), intent(in) :: names(:)
        type(status_type), intent(out) :: status
        character(len=CHARSET_NAME_LEN), allocatable :: sorted(:)
        integer, allocatable :: rank(:)
        character(len=CHARSET_NAME_LEN) :: t
        integer :: i, j, id, r

        allocate (sorted(size(names)), rank(size(names)))

        do i = 1, size(names)
            id = check_charset(trim(names(i)), status)
            if (id == 0) return
            sorted(i) = names(i)
            rank (i) = findloc(ordered(1:nordered), id, dim=1)
        end do

        do i = 2, size(sorted)
            t = sorted(i)
            r = rank(i)
            j = i - 1

            do while (j >= 1)
                if (rank(j) <= r) exit
                sorted(j + 1) = sorted(j)
                rank (j + 1) = rank(j)
                j = j - 1
            end do

            sorted(j + 1) = t
            rank (j + 1) = r
        end do
    end function sort_charsets

    !> Unify the characters of CHARSET with Unicode by its `:unify-map'
    !> (or UNIFY_MAP), or with DEUNIFY undo that.  Port of
    !> charset.c:Funify_charset.
    subroutine unify_charset(charset, status, unify_map, deunify)
        character(len=*), intent(in) :: charset
        type(status_type), intent(out) :: status
        character(len=*), intent(in), optional :: unify_map
        logical, intent(in), optional :: deunify
        logical :: undo
        integer :: id, i

        id = check_charset(charset, status)
        if (id == 0) return
        undo = .false.
        if (present(deunify)) undo = deunify

        associate (cs => charsets(id))
            if (.not. undo) then
                if (cs%unified_p .and. cs%deunifier_loaded) return
            else
                if (.not. cs%unified_p) return
            end if

            cs%unified_p = .false.

            if (.not. undo) then
                if (cs%method /= METHOD_OFFSET .or. cs%code_offset < 1114112) then
                    call set_error(status, FM_GENERIC_ERROR, "Can't unify charset: "//charset)
                    return
                end if

                if (present(unify_map)) then
                    cs%unify_map = unify_map
                    cs%unifier_loaded = .false.
                    cs%deunifier_loaded = .false.
                end if

                if (nunified == size(unified)) unified = [unified, [(0, i=1, size(unified))]]
                nunified = nunified + 1
                unified(nunified) = id
                cs%unified_p = .true.
            else
                do i = nunified, 1, -1
                    if (unified(i) == id) then
                        unified(i:nunified - 1) = unified(i + 1:nunified)
                        nunified = nunified - 1
                        exit
                    end if
                end do
            end if
        end associate
    end subroutine unify_charset

    !> Call FUNCTION with each range of characters of CHARSET whose code
    !> points are between FROM_CODE and TO_CODE (the whole charset when
    !> omitted).  Port of charset.c:Fmap_charset_chars and
    !> map_charset_chars.
    subroutine map_charset_chars(function, charset, status, from_code, to_code)
        procedure(charset_range_proc) :: function
        character(len=*), intent(in) :: charset
        type(status_type), intent(out) :: status
        integer(int64), intent(in), optional :: from_code, to_code
        integer(int64) :: from, to
        integer :: id

        id = check_charset(charset, status)
        if (id == 0) return
        from = charsets(id)%min_code

        if (present(from_code)) then
            if (from_code >= 0) from = max(from_code, charsets(id)%min_code)
        end if

        to = charsets(id)%max_code

        if (present(to_code)) then
            if (to_code >= 0) to = min(to_code, charsets(id)%max_code)
        end if

        call map_charset_chars_id(function, id, from, to, status)
    end subroutine map_charset_chars

    recursive subroutine map_charset_chars_id(function, id, from_code, to_code, status)
        procedure(charset_range_proc) :: function
        integer, intent(in) :: id
        integer(int64), intent(in) :: from_code, to_code
        type(status_type), intent(inout) :: status
        integer(int64) :: from, to, this_from, this_to
        integer :: i, parent, offset
        logical :: partial, ok

        from = from_code
        to = to_code
        partial = from > charsets(id)%min_code .or. to < charsets(id)%max_code

        select case (charsets(id)%method)
        case (METHOD_OFFSET)
            if (charsets(id)%unified_p) then
                if (.not. charsets(id)%deunifier_loaded) then
                    call load_charset(id, 2, ok, status)
                    if (.not. ok) return
                end if

                call map_table(charsets(id)%deunifier_chars)
            end if

            call function(int(code_point_to_index(charsets(id), from)) + charsets(id)%code_offset, &
                          int(code_point_to_index(charsets(id), to)) + charsets(id)%code_offset)
        case (METHOD_MAP)
            if (.not. charsets(id)%encoder_loaded) then
                call load_charset(id, 2, ok, status)
                if (.not. ok) return
            end if

            call map_table(charsets(id)%encoder_chars)
        case (METHOD_SUBSET)
            parent = charsets(id)%subset_parent
            offset = int(charsets(id)%subset_offset)
            from = from - offset
            if (from < charsets(id)%subset_min) from = charsets(id)%subset_min
            to = to - offset
            if (to > charsets(id)%subset_max) to = charsets(id)%subset_max
            call map_charset_chars_id(function, parent, from, to, status)
        case default
            do i = 1, size(charsets(id)%superset_ids)
                parent = charsets(id)%superset_ids(i)
                offset = charsets(id)%superset_offsets(i)
                this_from = max(0_int64, from - offset)
                this_to = max(0_int64, to - offset)
                if (this_from < charsets(parent)%min_code) this_from = charsets(parent)%min_code
                if (this_to > charsets(parent)%max_code) this_to = charsets(parent)%max_code
                call map_charset_chars_id(function, parent, this_from, this_to, status)
            end do
        end select

    contains

        ! The runs of consecutive characters of CHARS (sorted), each of
        ! whose code points is between FROM and TO when PARTIAL.  Port of
        ! chartab.c:map_char_table_for_charset.
        subroutine map_table(chars)
            integer, intent(in) :: chars(:)
            integer :: k, start, prev
            integer(int64) :: code
            logical :: in_range

            start = -1
            prev = -2

            do k = 1, size(chars)
                in_range = .true.

                if (partial) then
                    code = encode_char_id(id, chars(k), status)
                    in_range = code >= from .and. code <= to
                end if

                if (start >= 0 .and. (.not. in_range .or. chars(k) /= prev + 1)) then
                    call function(start, prev)
                    start = -1
                end if

                if (in_range) then
                    if (start < 0) start = chars(k)
                    prev = chars(k)
                end if
            end do

            if (start >= 0) call function(start, prev)
        end subroutine map_table
    end subroutine map_charset_chars_id

    !> The charsets of the characters between BEG and END in the current
    !> buffer, in the order of their definition (only `ascii' and
    !> `eight-bit' in a unibyte buffer).  Port of
    !> charset.c:Ffind_charset_region (translation tables are Deferred).
    function find_charset_region(beg, end, status) result(names)
        integer(int64), intent(in) :: beg, end
        type(status_type), intent(out) :: status
        character(len=CHARSET_NAME_LEN), allocatable :: names(:)
        logical, allocatable :: seen(:)
        integer(int64) :: from, to, stop
        character(len=:), allocatable :: text

        call syms_of_charset()
        allocate (names(0), seen(ncharsets))
        seen = .false.
        from = min(beg, end)
        to = max(beg, end)

        associate (b => buffers(cur))
            if (from < b%begv .or. to > b%zv) then
                call set_error(status, FM_ARGS_OUT_OF_RANGE, int_text(beg)//", "//int_text(end))
                return
            end if

            stop = to
            if (from < b%text%gpt .and. b%text%gpt < to) stop = b%text%gpt

            do
                text = buf_bytes(b, char_to_byte(from), char_to_byte(stop))
                call find_charsets_in_text(text, stop - from, b%multibyte, seen)

                if (stop < to) then
                    from = stop
                    stop = to
                else
                    exit
                end if
            end do
        end associate

        names = seen_names(seen)
    end function find_charset_region

    !> The charsets of the characters of STR, in the order of their
    !> definition.  STR is multibyte when MULTIBYTE says so; by default
    !> when it has a non-ASCII byte, as a string read by Emacs is.  Port of
    !> charset.c:Ffind_charset_string.
    function find_charset_string(str, multibyte) result(names)
        character(len=*), intent(in) :: str
        logical, intent(in), optional :: multibyte
        character(len=CHARSET_NAME_LEN), allocatable :: names(:)
        logical, allocatable :: seen(:)
        logical :: mb
        integer(int64) :: nchars, p
        integer :: c, length

        call syms_of_charset()
        allocate (seen(ncharsets))
        seen = .false.
        mb = .false.

        do p = 1, len(str, kind=int64)
            if (iachar(str(p:p)) >= 128) mb = .true.
        end do

        if (present(multibyte)) mb = multibyte
        nchars = len(str, kind=int64)

        if (mb) then
            nchars = 0
            p = 1

            do while (p <= len(str, kind=int64))
                call string_char_and_length(str, p, c, length)
                p = p + length
                nchars = nchars + 1
            end do
        end if

        call find_charsets_in_text(str, nchars, mb, seen)
        names = seen_names(seen)
    end function find_charset_string

    ! Port of charset.c:find_charsets_in_text.
    subroutine find_charsets_in_text(text, nchars, multibyte, seen)
        character(len=*), intent(in) :: text
        integer(int64), intent(in) :: nchars
        logical, intent(in) :: multibyte
        logical, intent(inout) :: seen(:)
        type(status_type) :: status
        integer(int64) :: p, code
        integer :: c, length, id

        if (nchars == len(text, kind=int64)) then
            if (multibyte) then
                seen(charset_ascii) = .true.
            else
                do p = 1, len(text, kind=int64)
                    if (iachar(text(p:p)) < 128) then
                        seen(charset_ascii) = .true.
                    else
                        seen(charset_eight_bit) = .true.
                    end if
                end do
            end if

            return
        end if

        p = 1

        do while (p <= len(text, kind=int64))
            call string_char_and_length(text, p, c, length)
            p = p + length
            id = char_charset_macro(c, code, status)
            if (id /= 0) seen(id) = .true.
        end do
    end subroutine find_charsets_in_text

    function seen_names(seen) result(names)
        logical, intent(in) :: seen(:)
        character(len=CHARSET_NAME_LEN), allocatable :: names(:)
        integer :: i, n

        allocate (names(count(seen)))
        n = 0

        do i = 1, size(seen)
            if (seen(i)) then
                n = n + 1
                names(n) = charsets(i)%name
            end if
        end do
    end function seen_names

    function int_text(n) result(text)
        integer(int64), intent(in) :: n
        character(len=:), allocatable :: text
        character(len=24) :: buf

        write (buf, "(i0)") n
        text = trim(buf)
    end function int_text
end module charset_fm
