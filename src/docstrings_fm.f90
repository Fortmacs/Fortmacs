    function repr_logical(v) result(s)
        logical, intent(in) :: v
        character(len=:), allocatable :: s
        s = merge(".true. ", ".false.", v)
        s = trim(s)
    end function repr_logical

    function repr_integer(v) result(s)
        integer, intent(in) :: v
        character(len=:), allocatable :: s
        character(len=12) :: buf
        write (buf, "(i0)") v
        s = trim(buf)
    end function repr_integer

    function repr_int64(v) result(s)
        integer(int64), intent(in) :: v
        character(len=:), allocatable :: s
        character(len=21) :: buf
        write (buf, "(i0)") v
        s = trim(buf)
    end function repr_int64

    !> An array of integers as a Fortran array constructor.
    function repr_int64s(v) result(s)
        integer(int64), intent(in) :: v(:)
        character(len=:), allocatable :: s
        integer :: i
        s = "["
        do i = 1, size(v)
            if (i > 1) s = s//", "
            s = s//repr_int64(v(i))
        end do
        s = s//"]"
    end function repr_int64s

    !> A string as a Fortran literal.
    function repr_string(v) result(s)
        character(len=*), intent(in) :: v
        character(len=:), allocatable :: s
        integer :: i
        s = """"
        do i = 1, len_trim(v)
            s = s//v(i:i)
            if (v(i:i) == """") s = s//""""
        end do
        s = s//""""
    end function repr_string

    !> An array of strings as a Fortran array constructor.
    function repr_strings(v) result(s)
        character(len=*), intent(in) :: v(:)
        character(len=:), allocatable :: s
        integer :: i
        s = "["
        do i = 1, size(v)
            if (i > 1) s = s//", "
            s = s//repr_string(v(i))
        end do
        s = s//"]"
    end function repr_strings
